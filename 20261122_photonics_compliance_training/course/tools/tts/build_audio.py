"""Pre-record every line the engine can speak: Kokoro-82M clips keyed by LMS_hash(text) (COURSE_SPEC.md,
"Recorded voice (Kokoro)"; DevLog-003).

Run (from course/):
  uv run --no-project --with kokoro-onnx --with pyloudnorm python tools/tts/build_audio.py \
    [--dry-run] [--course ferroelectric] [--chapter welcome] [--limit N] [--voice af_heart] [--speed 1.0] \
    [--threads 4] [--redo REGEX] [--list-orphans]

Strings: node tools/tts/extract.js (engine/speech_lines.js LMS_collectSpeech when present, else a fallback walker).
Per string: pronounce.say_text (+ IPA overrides) -> Kokoro -> trim -> tail fix (final t/k/p) -> -18 LUFS ->
high-pass 70 Hz + limiter -1.5 dBFS -> MP3 mono 24 kHz 64 kb/s -> audio/<hash>.mp3 (written via .part, then renamed).
Resumable: a clip is skipped when audio/<hash>.mp3 exists and tools/tts/clips_index.json records the same voice,
speed and spoken text (so a pronunciation-map change re-renders only the clips it affects). --redo REGEX forces
re-rendering of matching lines. The manifest audio/manifest.js is rewritten every 25 clips and at the end, from the
full string list (all courses) and the clips present on disk, so a --course / --chapter run never drops other clips.
Nothing is deleted; --list-orphans prints clips on disk that no current line uses.
Log: tools/tts/logs/build_audio_<YYYYmmdd_HHMMSS>.jsonl (one row per clip, then a summary row).
CPU: one Kokoro session with --threads intra-op threads (max 4); clips are processed one at a time.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import pronounce  # noqa: E402
import tts_common as T  # noqa: E402
from speech_hash import lms_hash  # noqa: E402

COURSE = os.path.abspath(os.path.join(HERE, "..", ".."))
AUDIO = os.path.join(COURSE, "audio")
MANIFEST = os.path.join(AUDIO, "manifest.js")
INDEX = os.path.join(HERE, "clips_index.json")
DEFAULT_VOICE = "af_heart"
# measured on the af_heart 1.0 pilot, 2026-11-22 (FE welcome module + engine lines, 66 clips): 907 words in 324.7 s
# of clip audio = 167.6 words per minute; MP3 64 kb/s = 0.48 MB per minute (pilot measured 0.489)
WPM_EST = 167.6
MB_PER_MIN = 64e3 / 8 * 60 / 1e6


def extract(course=None, chapter=None):
    cmd = ["node", os.path.join(HERE, "extract.js")]
    if course:
        cmd += ["--course", course]
    if chapter:
        cmd += ["--chapter", chapter]
    r = subprocess.run(cmd, capture_output=True, text=True, check=True)
    if r.stderr.strip():
        print(r.stderr.strip(), file=sys.stderr)
    return json.loads(r.stdout)


def read_manifest():
    if not os.path.exists(MANIFEST):
        return {}
    s = open(MANIFEST).read()
    m = re.search(r"=\s*(\{.*\})\s*;?\s*$", s, re.S)
    return json.loads(m.group(1)) if m else {}


def write_manifest(voice, all_hashes, index):
    files = {}
    for h in sorted(all_hashes):
        if os.path.exists(os.path.join(AUDIO, h + ".mp3")) and h in index:
            files[h] = index[h]["s"]
    body = json.dumps({"voice": voice, "ext": "mp3", "files": files}, indent=0, sort_keys=False)
    tmp = MANIFEST + ".part"
    with open(tmp, "w") as f:
        f.write("/* Generated by tools/tts/build_audio.py; do not edit. Clip seconds by LMS_hash(text). */\n")
        f.write("window.LMS_AUDIO = " + body + ";\n")
    os.replace(tmp, MANIFEST)
    return files


def probe_seconds(path):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                       capture_output=True, text=True)
    try:
        return round(float(r.stdout.strip()), 2)
    except ValueError:
        return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--course")
    ap.add_argument("--chapter")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--voice", default=None)
    ap.add_argument("--speed", type=float, default=1.0)
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--redo", default="")
    ap.add_argument("--list-orphans", action="store_true")
    a = ap.parse_args()
    a.threads = max(1, min(4, a.threads))

    man = read_manifest()
    voice = a.voice or man.get("voice") or DEFAULT_VOICE
    index = json.load(open(INDEX)) if os.path.exists(INDEX) else {}
    full = extract()
    all_hashes = {x["hash"] for x in full["voice_lines"]}
    sel = extract(a.course, a.chapter) if (a.course or a.chapter) else full
    lines = sel["voice_lines"]
    for x in lines:   # cross-check the Python twin on every string
        assert lms_hash(x["text"]) == x["hash"], ("hash mismatch JS vs Python", x["text"])

    if a.list_orphans:
        on_disk = {f[:-4] for f in os.listdir(AUDIO) if f.endswith(".mp3")} if os.path.isdir(AUDIO) else set()
        orph = sorted(on_disk - all_hashes)
        print("%d clips on disk, %d used, %d orphans" % (len(on_disk), len(on_disk & all_hashes), len(orph)))
        for h in orph:
            print(h, index.get(h, {}).get("text", "")[:100])
        return

    redo = re.compile(a.redo) if a.redo else None
    todo, mapped = [], 0
    for x in lines:
        say = pronounce.say_text(x["text"])
        x["say"] = say
        x["ipa"] = pronounce.needs_ipa(say)
        mapped += (say != x["text"]) or x["ipa"]
        e = index.get(x["hash"])
        have = os.path.exists(os.path.join(AUDIO, x["hash"] + ".mp3"))
        fresh = have and e and e.get("voice") == voice and e.get("speed") == a.speed and e.get("say") == say and e.get("ipa") == x["ipa"] \
            and e.get("lufs") == T.TARGET_LUFS
        if not fresh or (redo and redo.search(x["text"])):
            todo.append(x)
    if a.limit:
        todo = todo[:a.limit]
    words = sum(len(x["text"].split()) for x in lines)
    words_todo = sum(len(x["text"].split()) for x in todo)
    est_min = words / WPM_EST
    print("source %s | courses %s | voice %s speed %.2f" % (sel["source"], ",".join(sel["courses"]) if not a.course else a.course, voice, a.speed))
    print("selected lines %d, words %d, est. speech %.1f min, est. MP3 %.1f MB; changed by pronunciation map: %d" % (
        len(lines), words, est_min, est_min * MB_PER_MIN, mapped))
    print("to synthesize: %d lines, %d words (est. %.1f min of audio)" % (len(todo), words_todo, words_todo / WPM_EST))
    if a.dry_run:
        by_course = {}
        for x in lines:
            for c in x["courses"]:
                d = by_course.setdefault(c, [0, 0])
                d[0] += 1
                d[1] += len(x["text"].split())
        for c, (n, w) in sorted(by_course.items()):
            print("  %-14s lines %4d  words %6d  est. %.1f min  %.1f MB" % (c, n, w, w / WPM_EST, w / WPM_EST * MB_PER_MIN))
        print("dry run: nothing written")
        return

    import numpy as np  # noqa: F401
    from kokoro_onnx.tokenizer import Tokenizer
    os.makedirs(AUDIO, exist_ok=True)
    if not todo:
        files = write_manifest(voice, all_hashes, index)
        print("nothing to synthesize; manifest has %d of %d lines" % (len(files), len(all_hashes)))
        return
    os.makedirs(os.path.join(HERE, "logs"), exist_ok=True)
    logp = os.path.join(HERE, "logs", "build_audio_%s.jsonl" % time.strftime("%Y%m%d_%H%M%S"))
    log = open(logp, "w")
    if man.get("voice") and man["voice"] != voice and man.get("files"):
        print("note: manifest voice %s -> %s; clips of the old voice are re-rendered as they come up" % (man["voice"], voice))
    t_load = time.time()
    k, tok = T.load_kokoro(a.threads), Tokenizer()
    t_load = time.time() - t_load
    tot_audio = tot_synth = tot_bytes = 0.0
    t0 = time.time()
    for i, x in enumerate(todo):
        ts = time.time()
        clip, info, sayinfo = T.render(k, tok, x["text"], voice, a.speed)
        t_syn = time.time() - ts
        out = os.path.join(AUDIO, x["hash"] + ".mp3")
        T.encode_mp3(clip, out)
        sec = round(len(clip) / T.KSR, 2)
        nb = os.path.getsize(out)
        index[x["hash"]] = {"text": x["text"], "say": x["say"], "ipa": x["ipa"], "voice": voice, "speed": a.speed, "lufs": T.TARGET_LUFS, "s": sec,
                            "bytes": nb, "date": time.strftime("%Y-%m-%d")}
        tot_audio += sec
        tot_synth += t_syn
        tot_bytes += nb
        row = {"i": i, "hash": x["hash"], "courses": x["courses"], "words": len(x["text"].split()), "s": sec, "bytes": nb,
               "synth_s": round(t_syn, 3), "wall_s": round(time.time() - ts, 3), **info, "say": x["say"], "ipa": x["ipa"]}
        log.write(json.dumps(row, ensure_ascii=False) + "\n")
        log.flush()
        if (i + 1) % 25 == 0 or i + 1 == len(todo):
            json.dump(index, open(INDEX + ".part", "w"), indent=0, ensure_ascii=False)
            os.replace(INDEX + ".part", INDEX)
            write_manifest(voice, all_hashes, index)
            el = time.time() - t0
            print("%d/%d  audio %.1f s  synth RTF %.3f  wall %.0f s  ETA %.0f s" % (
                i + 1, len(todo), tot_audio, tot_synth / max(tot_audio, 1e-9), el, el / (i + 1) * (len(todo) - i - 1)), flush=True)
    files = write_manifest(voice, all_hashes, index)
    wall = time.time() - t0
    summ = {"summary": True, "voice": voice, "speed": a.speed, "clips": len(todo), "audio_s": round(tot_audio, 2),
            "synth_s": round(tot_synth, 2), "wall_s": round(wall, 2), "model_load_s": round(t_load, 2),
            "rtf_synth": round(tot_synth / max(tot_audio, 1e-9), 4), "rtf_wall": round(wall / max(tot_audio, 1e-9), 4),
            "bytes": int(tot_bytes), "mb_per_audio_min": round(tot_bytes / 1e6 / max(tot_audio / 60, 1e-9), 3),
            "manifest_files": len(files), "manifest_lines_total": len(all_hashes)}
    log.write(json.dumps(summ) + "\n")
    log.close()
    print(json.dumps(summ))
    print("log", os.path.relpath(logp, COURSE))


if __name__ == "__main__":
    main()
