"""Event overrides for the v4 patch with M's doubled assembly (M v4.2, 288 build frames, 184-frame slot) (DevLog-014 section 17).

Run (project root): uv run --no-project python scripts/audio/make_overrides_v4c.py [--slot-start 47.9]
Writes scripts/audio/event_overrides_v4c.json: the v4 decisions (door 44.23 and two extra satellite pings dropped,
scooter zoom added) plus a drop_window for S's "assembly_*" events in the slot and M's events from
assets/components/assembly/assembly_hatchery.json "events" at film t = slot_start + build_frame / 1.5652 / 30
(provisional until S's scene_events.json confirms them; then rebuild with S's slot start).
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from audio_util import HERE, PROJ, rel  # noqa: E402

SPEED, FPS = 1.5652, 30.0
ASM = os.path.join(PROJ, "assets", "components", "assembly", "assembly_hatchery.json")

# (event key, kind, name, extra)
CUES = [
    ("S2_iso_place", "place_click", "asm_isolator_placed", {"params": {"f": 4200}}),
    ("S2_lens2_place", "place_click", "asm_lens_placed", {"params": {"f": 4700}}),
    ("S2_tool_leaves_lens", "align_stage", "asm_tool_leaves_lens", {"dur": 0.25, "gain": 0.8}),
    ("S2_dfb_on", "dfb_on", "asm_dfb_on", {"gain": 0.6}),
    ("S2_power_peak", "hud_tick", "asm_power_peak", {"params": {"f": 2200}}),
    ("S2_uv_on", "uv_cure", "asm_uv_cure", {"dur": 0.3}),
    ("S4_dispense_start", "pneumatic", "asm_dispense", {"dur": 0.5, "gain": 0.6, "params": {"dir": "up"}}),
    ("S4_press_down", "pneumatic", "asm_press_down", {"dur": 0.35}),
    ("S4_lid_closed", "lid_press", "asm_lid_closed", {"gain": 1.2}),
    ("S4_platen_up", "pneumatic", "asm_press_up", {"dur": 0.35, "params": {"dir": "up"}}),
    ("S5_seat_hop", "hop", "asm_hop_into_socket", {}),
    ("S5_feet_seated", "place_click", "asm_feet_seated", {"params": {"f": 2600}}),
    ("S5_power_on", "pad_charge_hum", "asm_power_on", {"dur": 0.4, "gain": 0.7}),
    ("S5_eyes_on", "eye_glow_on", "asm_eyes_on", {"dur": 0.45}),
    ("S5_cmis_id", "hud_tick", "asm_cmis_id", {"params": {"f": 1700}}),
    ("S5_cmis_ready", "hud_tick", "asm_cmis_ready", {"params": {"f": 2100}}),
    ("S5_heads_in", "coupler_in", "asm_heads_in", {"dur": 0.3}),
    ("S5_heads_docked", "cell_dock", "asm_heads_docked", {"gain": 0.7, "dur": 0.35}),
    ("S5_rx_sweep_on", "pic_lightup", "asm_rx_sweep", {"dur": 0.3, "gain": 0.6}),
    ("S5_full_link_on", "link_blip", "asm_full_link_on", {"gain": 1.6}),
    ("S5_pass", "pass_chime", "asm_pass", {}),
    ("S5_heads_out", "coupler_out", "asm_heads_out", {"dur": 0.35}),
    ("S5_hop1", "hop", "asm_hop_off", {}),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slot-start", type=float, default=47.867)
    ap.add_argument("--shift", type=float, default=3.067, help="S6/S7 shift vs v4 (doubled slot)")
    ap.add_argument("--out", default=os.path.join(HERE, "event_overrides_v4c.json"))
    args = ap.parse_args()
    A = json.load(open(ASM))["events"]
    t = lambda f: round(args.slot_start + f / SPEED / FPS, 3)  # noqa: E731
    slot_end = round(args.slot_start + 288 / SPEED / FPS, 3)
    add = [dict({"t": t(A[k]), "name": n, "kind": kind}, **x) for k, kind, n, x in CUES]
    lanes0, lanes1 = A["S5_full_link_on"], A["S5_full_link_lanes_done"]
    add.append({"t": t(lanes0), "name": "asm_lanes_up", "kind": "lane_ticks", "dur": round((lanes1 - lanes0) / SPEED / FPS, 3), "params": {"count": 8}})
    bonds = [A[k] for k in sorted(A) if k.startswith("S3_bond_") and k[8:].isdigit()][::3]   # 34 bonds -> every 3rd (texture)
    for i in range(1, 9):
        add.append({"t": t(A["S5_tx_lane_%d" % i]), "name": "asm_tx_lane_%d" % i, "kind": "pd_flash", "gain": 0.8,
                    "params": {"f": 1800 * 2 ** (i / 8)}})
    for i in range(1, 5):
        add.append({"t": t(A["S5_psu_current_step_%d" % i]), "name": "asm_psu_step_%d" % i, "kind": "crystal_tick", "gain": 0.7})
    add += [{"t": t(f), "name": "asm_wire_bond_%d" % i, "kind": "wire_bonder", "gain": 0.6} for i, f in enumerate(bonds)]
    add.append({"t": round(60.35 + args.shift, 3), "name": "scooter_zoom_to_card", "kind": "scooter_zoom", "dur": 0.7, "params": {"peak": 0.92}})
    ov = {
        "_doc": "Overrides for the v4 patch (M's rebuilt test stand), generated by scripts/audio/make_overrides_v4c.py from %s, slot start %.3f s (provisional until S's events confirm). drop / drop_window applied before add." % (rel(ASM), args.slot_start),
        "drop": [
            {"name": "subject_exits_door", "t": 44.23, "tol": 0.05},
            {"name": "satellite_handoff_1", "t": round(56.47 + args.shift, 3), "tol": 0.06},
            {"name": "satellite_handoff_3", "t": round(56.93 + args.shift, 3), "tol": 0.06}],
        "drop_window": [{"prefix": "assembly_", "t0": args.slot_start - 0.3, "t1": slot_end + 0.3}],
        "add": sorted(add, key=lambda e: e["t"]),
    }
    with open(args.out, "w") as f:
        f.write("{\n" + ",\n".join(" %s: %s" % (json.dumps(k), json.dumps(v) if not isinstance(v, list) else "[\n" + ",\n".join("  " + json.dumps(x) for x in v) + "\n ]") for k, v in ov.items()) + "\n}\n")
    print("slot %.3f-%.3f s, %d added events -> %s" % (args.slot_start, slot_end, len(add), rel(args.out)))
    for e in ov["add"]:
        print("  %6.3f %-12s %s" % (e["t"], e["kind"], e["name"]))


if __name__ == "__main__":
    main()
